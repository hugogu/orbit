export function pickCuriosities(
  previous: unknown,
  random: () => number = Math.random,
): Record<string, number> {
  const saved =
    previous && typeof previous === 'object'
      ? (previous as Record<string, unknown>)
      : {};
  return Object.fromEntries(
    Object.entries(curiosities).map(([id, pool]) => {
      const last = saved[id];
      const valid =
        typeof last === 'number' &&
        Number.isInteger(last) &&
        last >= 0 &&
        last < pool.length;
      const count = pool.length - (valid ? 1 : 0);
      let next = Math.min(count - 1, Math.max(0, Math.floor(random() * count)));
      if (valid && next >= last) next++;
      return [id, next];
    }),
  );
}
